def sample_id(number):
    return f"<sample-{number:02d}@sample.test>"


def main():
    # Why: מוחקים קודם — save_email לא דורס קובץ קיים, וכך שינוי בתוכן נכנס בפועל
    for old in SAMPLE_EMAILS_DIR.glob("*.json"):
        old.unlink()
    for number, day, time, sender, subject, body, body_type, reply_to in MESSAGES:
        date = datetime.fromisoformat(f"{day}T{time}").replace(tzinfo=TZ)
        record = {
            "message_id": sample_id(number),
            "date": date.isoformat(),
            "subject": subject,
            "from": sender,
            "in_reply_to": sample_id(reply_to) if reply_to else None,
            "body": body,
            "body_type": body_type,
        }
        save_email(record, folder=SAMPLE_EMAILS_DIR)
    print("Saved:", len(list(SAMPLE_EMAILS_DIR.glob("*.json"))), "files in", SAMPLE_EMAILS_DIR)


if __name__ == "__main__":
    main()
